#!/usr/bin/env bash
# Generate source identity without adding a Python dependency to Linux builds.
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
output=${1:?Usage: bash tools/build-info.sh OUTPUT_HEADER}
version=$(cat "$root/VERSION")
[[ $version =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[A-Za-z0-9.-]+)?$ ]] || {
    echo 'Invalid VERSION (expected major.minor.patch with optional prerelease suffix)' >&2
    exit 1
}
commit=unknown
state=unknown
revision=unknown
# Do not accidentally identify an enclosing repository when building a source ZIP.
if [[ -e $root/.git ]] && git -C "$root" rev-parse --verify HEAD >/dev/null 2>&1; then
    commit=$(git -C "$root" rev-parse HEAD)
    revision=g${commit:0:12}
    state=clean
    if [[ -n $(git -C "$root" status --porcelain --untracked-files=normal) ]]; then
        state=dirty
        revision+=-dirty
    fi
fi
mkdir -p -- "$(dirname -- "$output")"
temporary=$(mktemp "${output}.XXXXXX")
trap 'rm -f -- "$temporary"' EXIT
cat >"$temporary" <<EOF
/* Generated by tools/build-info.sh; do not edit. */
#ifndef LINRAD_BUILD_INFO_H
#define LINRAD_BUILD_INFO_H
#define LINRAD_APP_VERSION "$version"
#define LINRAD_BUILD_ID "$version+$revision"
#define LINRAD_GIT_COMMIT "$commit"
#define LINRAD_SOURCE_STATE "$state"
#endif
EOF
# Recheck Git on every build, but leave no-op builds and object mtimes intact.
if ! cmp -s -- "$temporary" "$output"; then
    mv -- "$temporary" "$output"
fi
